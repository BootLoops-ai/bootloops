# lower incomplete gamma (regular part) as a 3-var order-2 jet
# ---------------------------------------------------------------------
def gamma_low_jet(s, x, order2):
    """gamma_low(s,x) jet: s, x are Jets (3-var). Kummer series with
    certified tails on EVERY component. Requires x.v > 0 and the s ball
    to exclude {0, -1, -2, ...} (checked)."""
    if not (x.v > 0):
        raise OracleRefusal("gamma_low", "x not provably > 0")
    # distance of s ball to the nearest pole (0, -1, -2)
    slo = None
    for k in range(0, 3):
        dk = (s.v + k).abs_lower()
        if not (dk > 0):
            raise OracleRefusal("gamma_low", f"s ball touches pole -{k}")
        slo = dk if slo is None or dk < slo else slo
    xu = x.v.abs_upper()
    W_up = arb(10).log().abs_upper()
    # per-jet-var first-derivative log-factor bound for term t_n:
    #   d/ds: sum_k 1/|s+k| <= (n+1)/slo;  d/dx routes (x = (t+c)/tau):
    #   |dlog t_n / d(lc or ltau)| <= n*W — combined majorant
    #   (n+1)*g1, g1 = 1/slo + W (sum >= max); second order: 2(n+1)^2 g1^2
    g1 = 1 / slo + W_up
    # t_0 = 1/s;  t_n = t_{n-1} * x / (s+n)
    t = s._recip()
    S = t
    tail_ok = False
    n = 0
    NMAX = 400
    eps = arb(2) ** (-200)
    while n < NMAX:
        n += 1
        t = t * x / (s + n)
        S = S + t
        u = xu / (n + 1)
        if u < 0.5:
            tval = t.v.abs_upper()
            base = tval * u / (1 - u)
            # value tail <= base; grad tail <= 2*base*(n+2)*g1/(1-u);
            # hess tail <= 8*base*(n+2)^2*g1^2/(1-u)^2 (u<1/2 majorants,
            # explicit safety factors)
            t0 = base
            t1 = 2 * base * (n + 2) * g1 / (1 - u)
            t2 = 8 * base * (n + 2) * (n + 2) * g1 * g1 \
                / (1 - u) / (1 - u)
            worst = t2
            if t1 > worst:
                worst = t1
            if t0 > worst:
                worst = t0
            if worst < eps * S.v.abs_lower() + eps:
                pad = arb(0, worst)
                S = Jet(S.v + pad,
                        [gg + pad for gg in S.g],
                        None if S.h is None else
                        [hh + pad for hh in S.h], S.n)
                tail_ok = True
                break
    if not tail_ok:
        raise OracleRefusal("gamma_low",
                            f"Kummer series no certified tail by {NMAX}")
    xs = (s * x.log()).exp()
    return xs * (-x).exp() * S


def _phi_expm1_jet(z, order2):
    """phi(z) = expm1(z)/z as a jet, safe when the z ball contains 0:
    for |z| provably < 0.5 use the series sum_{k>=0} z^k/(k+1)! with a
    certified all-component tail; else the direct expm1(z)/z."""
    zu = z.v.abs_upper()
    if zu < 0.5:
        S = Jet.const(arb(1), z.n, order2)
        t = Jet.const(arb(1), z.n, order2)
        fac = arb(1)
        K = 40
        for k in range(1, K + 1):
            t = t * z
            fac = fac / (k + 1)
            S = S + t * fac
        # tail: sum_{k>K} |z|^k/(k+1)! <= zu^{K+1}/(K+2)! * 1/(1-zu);
        # jet-derivative factors <= (k+1) per order (d/dz z^k = k z^{k-1},
        # |z|<1) — majorant 8*(K+3)^2 covers both orders (zu<1/2)
        pw = arb(1)
        for _ in range(K + 1):
            pw *= zu
        f = arb(1)
        for k in range(2, K + 3):
            f *= k
        # jet-component bound from the ACTUAL z jet (rigorous):
        zb = arb(1)
        for gcomp in z.g:
            zb += gcomp.abs_upper()
        if z.h is not None:
            for hcomp in z.h:
                zb += hcomp.abs_upper()
        tail = pw / f / (1 - zu) * 8 * zb * zb * (K + 3) * (K + 3)
        pad = arb(0, tail.abs_upper())
        return Jet(S.v + pad, [g + pad for g in S.g],
                   None if S.h is None else [h + pad for h in S.h], S.n)
    return z.expm1() / z


def delta_gamma_low_jet(s, x1, x2, order2):
    """DELTA of lower incomplete gammas, POLE-FREE at s = 0:
      gamma(s,x2) - gamma(s,x1)
        = sum_{n>=0} (-1)^n/n! * (x2^{s+n} - x1^{s+n})/(s+n)
    with the n = 0 term computed as e^{s L1} * (L2-L1) * phi(s (L2-L1)),
    phi = expm1(z)/z (the removable-singularity form; L = log x). Cures
    the s->0 width blow-up of the per-gamma Kummer route (JOURNAL gate
    catch #5: at the hi-target corners omega ~ +2e-4, each gamma's jet
    carries 1/s^3-scale components whose widths explode while the
    DIFFERENCE is finite). Requires x1, x2 provably > 0 and the s ball
    to exclude {-1, -2, ...} (s = 0 is FINE here); designed for the
    x <= ~1e-2 regime (fast alternating convergence; checked)."""
    if not (x1.v > 0) or not (x2.v > 0):
        raise OracleRefusal("delta_gamma", "x not provably > 0")
    if not (s.v.abs_upper() < 0.5):
        raise OracleRefusal("delta_gamma",
                            "|s| < 0.5 not provable (pole margin)")
    x2u = x2.v.abs_upper()
    x1u = x1.v.abs_upper()
    xu = x2u if x2u > x1u else x1u
    if not (xu < 0.01):
        raise OracleRefusal("delta_gamma",
                            "x outside the small-x design regime")
    L1 = x1.log()
    L2 = x2.log()
    dL = L2 - L1
    z = s * dL
    D0 = (s * L1).exp() * dL * _phi_expm1_jet(z, order2)
    S = D0
    # n >= 1 terms
    Lmax = L1.v.abs_upper()
    if L2.v.abs_upper() > Lmax:
        Lmax = L2.v.abs_upper()
    sign = -1
    fac = arb(1)
    N = 8
    for n in range(1, N + 1):
        fac = fac * n
        Dn = ((s + n) * L2).exp() - ((s + n) * L1).exp()
        Dn = Dn / (s + n)
        S = S + Dn * (sign / fac)
        sign = -sign
    # tail: |term_n| <= 2*xu^{n+s_lo}/((n-1)*n!) class; with s in
    # (-0.5, 0.5) and xu < 0.01, |x^{s+n}| <= xu^{n-0.5}; majorant with
    # jet-derivative factors <= (Lmax+2)(n+2) per order, safety 8
    pw = arb(1)
    for _ in range(N):
        pw *= xu          # xu^N  (>= xu^{N+1-0.5} for xu<1)
    facN = arb(1)
    for k in range(1, N + 2):
        facN *= k
    base = 4 * pw / facN / (1 - xu)
    gf = (Lmax + 2) * (N + 3)
    worst = base * 8 * gf * gf
    pad = arb(0, worst.abs_upper())
    return Jet(S.v + pad, [g + pad for g in S.g],
               None if S.h is None else [h + pad for h in S.h], S.n)


