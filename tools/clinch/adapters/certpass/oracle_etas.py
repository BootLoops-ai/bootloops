_G = {}      # worker globals set by fork


def _theta_balls(th_ser, prec):
    ctx.prec = prec
    return [deser(t) for t in th_ser]


def _pairs_chunk(args):
    """-sum_t log lam_t over targets [t0,t1) + its grad/hess pieces."""
    (t0, t1, th_ser, prec, order) = args
    d = _G
    th = _theta_balls(th_ser, prec)
    lmu, lk0, av, lc, om, lt, ld, gm, rho = th
    W = arb(10).log()
    mu = (lmu * W).exp()
    c = (lc * W).exp()
    tau = (lt * W).exp()
    itau = 1 / tau
    k0 = (lk0 * W).exp()
    dd = (ld * W).exp()
    one_om = 1 + om
    one_rho = 1 + rho
    muW = mu * W
    muW2 = muW * W
    # per-bin constants
    bins = d["bins"]                     # float dm values
    kap_b = []
    D_b = []
    dm_b = []
    for dmv in bins:
        dmb = arb(dmv)
        kap_b.append(k0 * (av * dmb).exp())
        D_b.append(dd * (gm * dmb).exp())
        dm_b.append(dmb)
    cW1om = c * W * one_om               # d3 = -cW1om * iP
    Witau = W * itau                     # d5 = Witau * dt
    W1rho = W * one_rho                  # d6 = -W1rho * q
    c33 = one_om * W * W * c             # h33 = -c33 * dt * iP^2
    cW = c * W                           # h34 = -cW * iP  (d/dom of d3... )
    W2 = W * W
    ps = d["ps"]; pt = d["pt"]
    pdt = d["pdt"]; pr2 = d["pr2"]; pbin = d["pbin"]
    tptr = d["tptr"]
    val = arb(0)
    grad = [arb(0) for _ in range(9)]
    hess = [[arb(0)] * 9 for _ in range(9)] if order >= 2 else None
    z = arb(0)
    for t in range(t0, t1):
        i0, i1 = tptr[t], tptr[t + 1]
        S0 = arb(0)
        S1 = [z] * 9
        S2 = [[z] * 9 for _ in range(9)] if order >= 2 else None
        for i in range(i0, i1):
            b = pbin[i]
            dt_ = arb(float(pdt[i]))
            r2 = arb(float(pr2[i]))
            P = dt_ + c
            iP = 1 / P
            L = P.log()
            Tv = (-dt_ * itau - one_om * L).exp()
            Db = D_b[b]
            R = r2 + Db
            iR = 1 / R
            M = R.log()
            q = Db * iR
            Sv = (-one_rho * M).exp()
            g = kap_b[b] * Tv * Sv
            dm = dm_b[b]
            d3 = -cW1om * iP
            d4 = -L
            d5 = Witau * dt_
            d6 = -W1rho * q
            d7 = -one_rho * dm * q
            d8 = -M
            dvec = (W, dm, d3, d4, d5, d6, d7, d8)   # indices 1..8
            S0 += g
            for k in range(8):
                S1[k + 1] = S1[k + 1] + g * dvec[k]
            if order >= 2:
                iP2 = iP * iP
                h33 = -c33 * dt_ * iP2
                h34 = -cW * iP
                h55 = -W * d5            # = -W^2 dt itau
                q1q = q * (1 - q)
                h66 = -one_rho * W2 * q1q
                h67 = -one_rho * W * dm * q1q
                h77 = -one_rho * dm * dm * q1q
                h68 = -W * q
                h78 = -dm * q
                hmap = {(3, 3): h33, (3, 4): h34, (5, 5): h55,
                        (6, 6): h66, (6, 7): h67, (7, 7): h77,
                        (6, 8): h68, (7, 8): h78}
                for k in range(8):
                    dk = dvec[k]
                    gk = g * dk
                    for l in range(k, 8):
                        e = dk * dvec[l]
                        hkl = hmap.get((k + 1, l + 1))
                        if hkl is not None:
                            e = e + hkl
                        S2[k + 1][l + 1] = S2[k + 1][l + 1] + g * e
        lam = mu + S0
        if not (lam > 0):
            raise OracleRefusal("lam_pos",
                                f"lam not provably > 0 at target {t}")
        il = 1 / lam
        val -= lam.log()
        gl = [muW] + [S1[k] for k in range(1, 9)]
        for k in range(9):
            grad[k] -= gl[k] * il
        if order >= 2:
            il2 = il * il
            Hl = [[z] * 9 for _ in range(9)]
            Hl[0][0] = muW2
            for k in range(1, 9):
                for l in range(k, 9):
                    Hl[k][l] = S2[k][l]
            for k in range(9):
                glk = gl[k]
                for l in range(k, 9):
                    hess[k][l] += glk * gl[l] * il2 - Hl[k][l] * il
    out = [ser(val)] + [ser(v) for v in grad]
    if order >= 2:
        for k in range(9):
            for l in range(k, 9):
                out.append(ser(hess[k][l]))
    return out


def _sources_chunk(args):
    """sum_j G_j over sources [j0,j1) + grad/hess pieces (9-dim)."""
    (j0, j1, th_ser, prec, order) = args
    d = _G
    th = _theta_balls(th_ser, prec)
    lmu, lk0, av, lc, om, lt, ld, gm, rho = th
    W = arb(10).log()
    order2 = order >= 2
    # jets in 3 vars (lc, om, ltau) for the TF factor
    lcj = jvar(lc, 0, 3, order2)
    omj = jvar(om, 1, 3, order2)
    ltj = jvar(lt, 2, 3, order2)
    cj = (lcj * W).exp()
    tj = (ltj * W).exp()
    itj = tj._recip()
    sj = -omj
    pref = (cj * itj).exp() * ((-omj) * (ltj * W)).exp()   # e^{c/tau} tau^-om
    src_m = d["src_m"]; src_ts = d["src_ts"]; src_te = d["src_te"]
    k0 = (lk0 * W).exp()
    dd = (ld * W).exp()
    irho = 1 / rho
    piA = arb.pi()
    lnD_base = ld * W        # lnD = ld*W + gm*dm
    val = arb(0)
    grad = [arb(0) for _ in range(9)]
    hess = [[arb(0)] * 9 for _ in range(9)] if order2 else None
    z = arb(0)
    # TF via the POLE-FREE difference series when x is in its design
    # regime (small x — the large-tau branch); else the per-gamma
    # Kummer route (JOURNAL gate catch #5)
    x1c_jet = cj * itj
    use_delta = bool((arb(float(np.max(d["src_te"]))) + cj.v).abs_upper()
                     * itj.v.abs_upper() < 0.01) and \
        bool(sj.v.abs_upper() < 0.5)
    gl_x1c = None if use_delta else gamma_low_jet(sj, x1c_jet, order2)
    # TF-block index map: jet vars (0,1,2) -> theta indices (3,4,5)
    JMAP = (3, 4, 5)
    HPAIRS3 = ((0, 0), (0, 1), (0, 2), (1, 1), (1, 2), (2, 2))
    for j in range(j0, j1):
        dm = arb(float(src_m[j]))        # already m - mc_min? no: m value
        dm = dm - d["mc_min_arb"]
        ts = float(src_ts[j])
        te = float(src_te[j])
        x2 = (arb(te) + cj) * itj
        x1 = x1c_jet if ts == 0.0 else (arb(ts) + cj) * itj
        if use_delta:
            TF = pref * delta_gamma_low_jet(sj, x1, x2, order2)
        else:
            gl2 = gamma_low_jet(sj, x2, order2)
            gl1 = gl_x1c if ts == 0.0 else gamma_low_jet(sj, x1, order2)
            TF = pref * (gl2 - gl1)
        # B = kappa * pi * D^-rho / rho ; log-linear pieces
        kap = k0 * (av * dm).exp()
        lnD = lnD_base + gm * dm
        Dmr = (-rho * lnD).exp()
        B = kap * piA * Dmr * irho
        Gv = B * TF.v
        val += Gv
        # dlogB over (lk0,a,ld,gam,rho) = (W, dm, -rho W, -rho dm,
        #                                  -lnD - 1/rho)
        dB = {1: W, 2: dm, 6: -rho * W, 7: -rho * dm, 8: -lnD - irho}
        for k, dv in dB.items():
            grad[k] += Gv * dv
        for m3 in range(3):
            grad[JMAP[m3]] += B * TF.g[m3]
        if order2:
            # hlogB nonzero: (6,8)=-W, (7,8)=-dm, (8,8)=irho^2
            hB = {(6, 8): -W, (7, 8): -dm, (8, 8): irho * irho}
            keys = sorted(dB.keys())
            for ii, k in enumerate(keys):
                for l in keys[ii:]:
                    e = dB[k] * dB[l]
                    hb = hB.get((k, l))
                    if hb is not None:
                        e = e + hb
                    hess[k][l] += Gv * e
            # TF second block
            for hidx, (m1, m2) in enumerate(HPAIRS3):
                hess[JMAP[m1]][JMAP[m2]] += B * TF.h[hidx]
            # cross dlogB x dTF
            for k, dv in dB.items():
                for m3 in range(3):
                    a_, b_ = sorted((k, JMAP[m3]))
                    hess[a_][b_] += dv * B * TF.g[m3]
    out = [ser(val)] + [ser(v) for v in grad]
    if order2:
        for k in range(9):
            for l in range(k, 9):
                out.append(ser(hess[k][l]))
    return out


def _init_worker(shared):
    _G.update(shared)


# ---------------------------------------------------------------------
class EtasOracle:
    """data: npz dict from etas_dump; part over the 9 theta coords."""

    def __init__(self, data, part, tag="", nworkers=10, prec=192):
        global LN10
        self.part = part
        self.tag = tag
        self.prec = prec
        self.nworkers = nworkers
        pt = np.asarray(data["pair_t"], np.int64)
        order = np.argsort(pt, kind="stable")
        self.pt = pt[order]
        self.ps = np.asarray(data["pair_s"], np.int64)[order]
        self.pdt = np.asarray(data["pair_dt"], float)[order]
        self.pr2 = np.asarray(data["pair_r2"], float)[order]
        pm = np.asarray(data["pair_m"], float)[order]
        self.mc_min = float(data["mc_min"])
        dmv = pm - self.mc_min
        bins, pbin = np.unique(np.round(dmv, 6), return_inverse=True)
        self.bins = bins
        self.pbin = pbin.astype(np.int32)
        self.n_t = int(len(data["trg_pbg"]))
        self.n_s = int(len(data["src_m"]))
        self.tptr = np.searchsorted(self.pt, np.arange(self.n_t + 1))
        self.src_m = np.asarray(data["src_m"], float)
        self.src_ts = np.asarray(data["src_ts"], float)
        self.src_te = np.asarray(data["src_te"], float)
        self.A = float(data["area"])
        self.T = float(data["tw_length"])
        self._pool = None
        LN10 = arb(10).log()

    @property
    def dims(self):
        return ([len(b) for b in self.part.blocks],
                len(self.part.border_idx))

    # ------------- box plumbing --------------------------------------
    def _theta_from_x(self, x):
        zs, g = x
        th = [None] * 9
        for bi, blk in enumerate(self.part.blocks):
            for pos, t in enumerate(blk):
                th[int(t)] = zs[bi][pos]
        for pos, t in enumerate(self.part.border_idx):
            th[int(t)] = g[pos]
        if any(v is None for v in th):
            raise OracleRefusal("partition", "part does not cover theta")
        return th

    def _shared(self):
        return dict(ps=self.ps, pt=self.pt, pdt=self.pdt, pr2=self.pr2,
                    pbin=self.pbin, tptr=self.tptr, bins=self.bins,
                    src_m=self.src_m, src_ts=self.src_ts,
                    src_te=self.src_te,
                    mc_min_arb=arb(self.mc_min))

    def _pool_get(self):
        import multiprocessing as mp
        if self._pool is None:
            ctxm = mp.get_context("fork")
            _init_worker(self._shared())     # also usable in-process
            self._pool = ctxm.Pool(self.nworkers)
        return self._pool

    def close(self):
        if self._pool is not None:
            self._pool.close()
            self._pool.join()
            self._pool = None

    def _eval(self, th, order):
        """(val, grad[9], hess[9][9] or None) — parallel over chunks."""
        th_ser = [ser(v) for v in th]
        prec = self.prec
        nw = self.nworkers
        # chunk targets by pair mass, sources evenly
        tb = np.linspace(0, self.n_t, 2 * nw + 1).astype(int)
        # balance: split by cumulative pairs
        cum = self.tptr
        total = cum[-1]
        marks = np.searchsorted(cum, np.linspace(0, total, 2 * nw + 1))
        marks[0] = 0
        marks[-1] = self.n_t
        marks = np.unique(marks)
        jobs = [( int(marks[i]), int(marks[i + 1]), th_ser, prec, order)
                for i in range(len(marks) - 1)]
        sb = np.linspace(0, self.n_s, nw + 1).astype(int)
        sjobs = [(int(sb[i]), int(sb[i + 1]), th_ser, prec, order)
                 for i in range(nw)]
        pool = self._pool_get()
        r1 = pool.map_async(_pairs_chunk, jobs)
        r2 = pool.map_async(_sources_chunk, sjobs)
        outs = r1.get() + r2.get()
        ctx.prec = prec
        val = arb(0)
        grad = [arb(0) for _ in range(9)]
        hess = [[arb(0)] * 9 for _ in range(9)] if order >= 2 else None
        for o in outs:
            val += deser(o[0])
            for k in range(9):
                grad[k] += deser(o[1 + k])
            if order >= 2:
                idx = 10
                for k in range(9):
                    for l in range(k, 9):
                        hess[k][l] += deser(o[idx])
                        idx += 1
        # mu * A * T term
        th_ = th
        W = arb(10).log()
        mu = (th_[0] * W).exp()
        AT = arb(self.A) * arb(self.T)
        val += mu * AT
        grad[0] += mu * W * AT
        if order >= 2:
            hess[0][0] += mu * W * W * AT
            for k in range(9):
                for l in range(k + 1, 9):
                    hess[l][k] = hess[k][l]
        if not val.is_finite():
            raise OracleRefusal("nonfinite_oracle", "value not finite")
        return val, grad, hess

    def sources_f64(self, th_float, order=2):
        """Float64 mids of the sources-side (sum G_j) value/grad/hess —
        the exact-register donor for the hybrid twin polish (no FD)."""
        ctx.prec = self.prec
        th = [arb(float(v)) for v in th_float]
        th_ser = [ser(v) for v in th]
        nw = self.nworkers
        sb = np.linspace(0, self.n_s, nw + 1).astype(int)
        sjobs = [(int(sb[i]), int(sb[i + 1]), th_ser, self.prec, order)
                 for i in range(nw)]
        pool = self._pool_get()
        outs = pool.map(_sources_chunk, sjobs)
        ctx.prec = self.prec
        val = 0.0
        grad = np.zeros(9)
        hess = np.zeros((9, 9)) if order >= 2 else None
        for o in outs:
            val += float(deser(o[0]).mid())
            for k in range(9):
                grad[k] += float(deser(o[1 + k]).mid())
            if order >= 2:
                idx = 10
                for k in range(9):
                    for l in range(k, 9):
                        hess[k][l] += float(deser(o[idx]).mid())
                        idx += 1
        if order >= 2:
            hess = np.triu(hess) + np.triu(hess, 1).T
        return val, grad, hess

    # ------------- engine-facing contract ----------------------------
    def nll(self, x):
        th = self._theta_from_x(x)
        v, _, _ = self._eval(th, 0)
        return v

    def _grad_full(self, x):
        th = self._theta_from_x(x)
        v, g, _ = self._eval(th, 1)
        return g, v

    def F(self, x):
        grad, _ = self._grad_full(x)
        Fz = [[grad[int(t)] for t in blk] for blk in self.part.blocks]
        Fg = [grad[int(t)] for t in self.part.border_idx]
        return Fz, Fg

    def F_full(self, x):
        return self.F(x)

    def H(self, x):
        from flint import arb_mat
        th = self._theta_from_x(x)
        _, _, Hfull = self._eval(th, 2)
        for a in range(9):
            for b in range(9):
                if not Hfull[a][b].is_finite():
                    raise OracleRefusal("nonfinite_oracle",
                                        f"H ({a},{b}) not finite")
        bi_ = self.part.border_idx
        D = []
        B = []
        for blk in self.part.blocks:
            D.append(arb_mat([[Hfull[int(s)][int(t)] for t in blk]
                              for s in blk]))
            B.append(arb_mat([[Hfull[int(s)][int(t)] for t in bi_]
                              for s in blk]))
        G = arb_mat([[Hfull[int(s)][int(t)] for t in bi_] for s in bi_])
        return D, B, G
