"""EtasOracle — ball-rigorous oracle for the ETAS (Ogata 1988) incomplete-data
(observed) negative log-likelihood as implemented in the etas package of
Mizrahi, Nandan & Wiemer (2021), the objective the package's EM
ascends (constant-background branch, xi = zeta = 1, receipted):

  NLL(th) = - sum_t log lam_t + mu*A*T + sum_j G_j
  lam_t   = mu + sum_{p in P(t)} g_p
  g_p     = kappa(m) * e^{-dt/tau} (dt+c)^{-(1+om)} * (r2+D(m))^{-(1+rho)}
  kappa   = k0 e^{a(m-mc_min)},  D = d e^{gamma(m-mc_min)}
  G_j     = kappa(m_j) * [pi D^-rho / rho] * TF_j
  TF_j    = int_{ts_j}^{te_j} e^{-t/tau} (t+c)^{-(1+om)} dt
          = e^{c/tau} tau^{-om} [ gamma_low(s,x2) - gamma_low(s,x1) ],
            s = -om, x_i = (t_i+c)/tau   (Gamma(s) cancels in the diff)

theta (9): [log10_mu, log10_k0, a, log10_c, omega, log10_tau, log10_d,
gamma, rho]. Pair table P(t) = the package's calculate_distances output,
regenerated by the pinned env and consumed by identity (etas_dump.py).

Pairs side: hand-assembled first/second log-derivatives (sparse exact
forms), accumulated per target then
combined through log. Sources side: 3-var second-order jets (clinch.jets
by identity) with gamma_low via the Kummer series
  gamma_low(s,x) = x^s e^{-x} sum_{n>=0} x^n / (s(s+1)...(s+n)),
run past value convergence with EXPLICIT tail enclosures on every jet
component (value/grad/hess tails bounded via sum (n+1)^2 |t_n| bounds and
the distance of the s ball to its nearest pole) — rigorous, no shrug.

Parallel: fork workers over target/source chunks; partial sums cross the
process boundary as EXACT (man, exp) integer quadruples (midpoint exact,
radius outward) — no lossy serialization.
"""
import os
import numpy as np
from flint import arb, ctx

from clinch.jets import Jet, jvar
from clinch.oracle_v31 import OracleRefusal

__all__ = ["EtasOracle", "Part", "OracleRefusal"]

LN10 = None


class Part:
    def __init__(self, blocks, block_names, border_idx):
        self.blocks = [np.asarray(b, dtype=int) for b in blocks]
        self.block_names = list(block_names)
        self.border_idx = np.asarray(border_idx, dtype=int)


# ---------------------------------------------------------------------
# exact serialization (man_exp quadruples)
# ---------------------------------------------------------------------
def ser(a):
    m, e = a.mid().man_exp()
    rm, re = a.rad().man_exp()
    return (int(m), int(e), int(rm), int(re))


def deser(t):
    m, e, rm, re = t
    mid = arb(m) * arb(2) ** e
    rad = arb(rm) * arb(2) ** re
    return arb(mid, rad)


