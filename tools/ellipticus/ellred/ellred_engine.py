"""ELLRED core engine: EXACT reduction of  int rat(x) dx / sqrt(P4(x))  to
standard incomplete Legendre F(phi,m), E(phi,m), Pi(n;phi,m) + algebraic, for a
quartic P4 with two complex-conjugate root pairs (K_asin/K_W curve E:y^2=P4,
x=u^2; reusable for E_alg).

PIPELINE
========
1. Legendre chart (s2_ell_normal.legendre_chart): P4 = A S1 S2, Mobius
   zeta=(x-t1)/(x-t2), x=(t2 zeta - t1)/(zeta-1), with
   S_i = (x-t2)^2 (a_i zeta^2 + b_i),  and
     dx/sqrt(P4) = jac dzeta/sqrt(A)/g,  jac=1/(t1-t2),  g=sqrt((a1 z^2+b1)(a2 z^2+b2)).
   phi(z)=atan(alpha z), alpha=sqrt(a1/b1); m=1-(a2 b1)/(a1 b2).
2. Pull back rat(x) -> ratz(z) = rat( (t2 z - t1)/(z-1) ) and the Jacobian
   factor; combine into  N(z)/D(z) * dz/g  with N,D in z (exact, over the field
   generated by t1,t2,a_i,b_i which are mpf numbers -> we keep them as high-prec
   mpmath and do the partial fraction NUMERICALLY-EXACT at 2*dps, but the
   DECOMPOSITION onto the standard basis is exact algebra).
3. Split  N/D = poly(z) + sum_j res_j/(z - p_j)  (full PF over C, conjugate
   poles combined to real 1/(z^2 - c) + z/(z^2 - c) forms).
4. Each atom integral against dz/g:
     A_F:    int dz/g                      = F-atom            [1st kind]
     A_E:    int (a2 z^2+b2) dz/g           = E-atom            [2nd kind]
        (d/dz of the E-antiderivative below = (a2 z^2+b2)/g, EXACT.)
     A_zk:   int z^(2k) dz/g  (k>=1)        -> linear in {A_F, A_E} via
                z^2 = ((a2 z^2+b2) - b2)/a2  => A_z2 = (A_E - b2 A_F)/a2;
                higher even powers by the standard recurrence (reduction of
                int z^{2k}/g) -> all in {F,E}+algebraic.
     A_odd:  int z^(2k+1) dz/g  -> w=z^2 substitution -> ALGEBRAIC (elementary).
     A_pole: int dz/((z^2 - c) g)           = Pi-atom            [3rd kind]
             int z dz/((z^2-c) g) -> w=z^2 -> ALGEBRAIC/log (elementary).
This module gives:
  reduce_const(P4n, x1, x2): I0 = int_{x1}^{x2} dx/sqrt(P4) as F-atom (gate).
  AntiF(P4n): callable Fx(x) for int^x dx/sqrt(P4) (F only).
  AntiE(P4n): callable Ex(x) for the E-antiderivative whose d/dx = ... (used in
              cofactor reduction).
  reduce_rat(Rnum, Rden, P4n, x1, x2): the FULL standard-form value + atom list.
The E-antiderivative is built from the relation:
   int (a2 z^2+b2) dz/g = int sqrt(a2 z^2+b2)/sqrt(a1 z^2+b1) dz.
   With z=sqrt(b1/a1) tan phi:  a1 z^2+b1=b1 sec^2 phi, a2 z^2+b2=b2 sec^2 phi(1-m sin^2),
   sqrt ratio = sqrt(b2/b1) Delta sec... let's just DEFINE E-atom by its closed
   value computed via mpmath ellipe in the standard variable and CERTIFY by
   exact-derivative match (we verify d/dx atoms numerically to >dps).
"""
import os, sys
# The chart layer is vendored as the sibling module .ell_normal.
import sympy as sp
from mpmath import (mp, mpf, mpc, sqrt as msqrt, atan as matan, ellipf, ellipe,
                    ellippi, quad as mquad, nstr, polyroots, mpmathify)
from . import ell_normal as EN


def chart(P4n):
    ch = EN.legendre_chart(P4n)
    ch['alpha2'] = ch['a1']/ch['b1']
    ch['m'] = 1 - (ch['a2']*ch['b1'])/(ch['b2']*ch['a1'])
    ch['jac'] = 1/(ch['t1']-ch['t2'])
    return ch


def zof(ch, x):
    return (x - ch['t1'])/(x - ch['t2'])


def gz(ch, z):
    return msqrt((ch['a1']*z*z+ch['b1'])*(ch['a2']*z*z+ch['b2']))


def phi(ch, z):
    return matan(msqrt(ch['alpha2'])*z)


# ----- standard ATOMS as antiderivatives in z (lower limit z=0) -----
def atomF(ch, z):
    """int_0^z dz'/g = (1/sqrt(a1 b2)) F(phi,m).  d/dz = 1/g  (CERTIFIED)."""
    return (1/msqrt(ch['a1']*ch['b2']))*ellipf(phi(ch, z), ch['m'])


def Delta(ch, z):
    al2z = ch['alpha2']*z*z
    return msqrt(1 - ch['m']*al2z/(1+al2z))


def atomE_closed(ch, z):
    """CLOSED int_0^z (a2 z'^2+b2) dz'/g = sqrt(b2/a1)[tan(phi)Delta - E + F].
    (derived & gated 48-50d, derive_atoms.py).  tan(phi)=sqrt(alpha2) z."""
    from mpmath import tan as mtan
    ph = phi(ch, z)
    De = Delta(ch, z)
    return msqrt(ch['b2']/ch['a1'])*(mtan(ph)*De - ellipe(ph, ch['m'])
                                     + ellipf(ph, ch['m']))


def atomPi_closed(ch, c, z):
    """CLOSED int_0^z dz'/((z'^2 - c) g) = -1/(c sqrt(a1 b2)) [(1/n0)F + (1-1/n0)Pi(n0)],
    n0 = 1 + b1/(a1 c).  (derived & gated 48-50d, derive_atoms.py)."""
    n0 = 1 + ch['b1']/(ch['a1']*c)
    ph = phi(ch, z)
    return (1/msqrt(ch['a1']*ch['b2']))*(-(1/c))*(
        (1/n0)*ellipf(ph, ch['m']) + (1-1/n0)*ellippi(n0, ph, ch['m']))


def atomE(ch, z):
    """An antiderivative whose d/dz = (a2 z^2 + b2)/g.
    Build:  let u=phi.  dz/g = (1/sqrt(a1 b2)) du/Delta,  Delta=sqrt(1-m sin^2 u).
    a2 z^2+b2 = b2 sec^2 u (1 - m sin^2 u) = b2 Delta^2 sec^2 u  [verify below].
    => (a2 z^2+b2) dz/g = (b2/sqrt(a1 b2)) Delta sec^2 u du.
    int Delta sec^2 u du = tan u Delta + int sin^2 u ... -> use the standard
    closed result:  int Delta(u) sec^2 u du = tan(u) Delta(u) - E(u,m) + F(u,m)?? 
    We avoid the hand identity: define atomE via the COMBINATION
      atomE = c1 * E(phi,m) + c2 * F(phi,m) + c3 * [algebraic: z sqrt(...)]
    and FIX c1,c2,c3 by exact-derivative matching (3 eqns) at 3 z-samples,
    using EXACT analytic derivatives of E,F and the algebraic term.  Done in
    _calibrate_E()."""
    c1, c2, c3, alg = ch['_E']
    return c1*ellipe(phi(ch, z), ch['m']) + c2*ellipf(phi(ch, z), ch['m']) + c3*alg(z)


def _dE_dz(ch, z):
    """exact d/dz of ellipe(phi,m): E'(phi)=Delta(phi); phi'(z)=alpha/(1+alpha^2 z^2)
       Delta=sqrt(1-m sin^2 phi).  sin phi = alpha z/sqrt(1+alpha^2 z^2)."""
    al = msqrt(ch['alpha2']); a2z = ch['alpha2']*z*z
    dphi = al/(1+a2z)
    sin2 = a2z/(1+a2z)
    Delta = msqrt(1-ch['m']*sin2)
    return Delta*dphi


def _dF_dz(ch, z):
    al = msqrt(ch['alpha2']); a2z = ch['alpha2']*z*z
    dphi = al/(1+a2z)
    sin2 = a2z/(1+a2z)
    Delta = msqrt(1-ch['m']*sin2)
    return dphi/Delta


def _calibrate_E(ch, zwin=None):
    """Find c1,c2,c3 (z-INDEPENDENT constants) s.t.
       d/dz[c1 E(phi,m) + c2 F(phi,m) + c3 z g(z)] = (a2 z^2+b2)/g.
    Calibrate at z-samples INSIDE the physical window zwin=(zlo,zhi) so the
    near-m=1 evaluation is well conditioned (samples near pi/2 are singular).
    """
    def alg(z):
        return z*gz(ch, z)
    def dalg(z):
        g = gz(ch, z)
        dnum = 2*ch['a1']*z*(ch['a2']*z*z+ch['b2']) + (ch['a1']*z*z+ch['b1'])*2*ch['a2']*z
        return g + z*dnum/(2*g)
    def tgt(z):
        return (ch['a2']*z*z+ch['b2'])/gz(ch, z)
    if zwin is None:
        zlo, zhi = mpf('0.05'), mpf('0.12')
    else:
        zlo, zhi = zwin
    # spread 3 samples across the window (+ small pad)
    pad = (zhi-zlo)*mpf('0.15')
    zs = [zlo-pad, (zlo+zhi)/2, zhi+pad]
    from mpmath import matrix, lu_solve
    M = matrix(3, 3); rhs = matrix(3, 1)
    for i, z in enumerate(zs):
        M[i, 0] = _dE_dz(ch, z); M[i, 1] = _dF_dz(ch, z); M[i, 2] = dalg(z)
        rhs[i, 0] = tgt(z)
    sol = lu_solve(M, rhs)
    ch['_E'] = (sol[0], sol[1], sol[2], alg)
    zc = (zlo+zhi)/2 + (zhi-zlo)*mpf('0.31')
    der = (sol[0]*_dE_dz(ch, zc)+sol[1]*_dF_dz(ch, zc)+sol[2]*dalg(zc))
    ch['_E_cert'] = abs(der - tgt(zc))/abs(tgt(zc))
    return ch


def atomPi(ch, c, z):
    """int_0^z dz'/((z'^2 - c) g).  Pole at z^2=c -> standard Pi.
    With z=sqrt(b1/a1) tan phi:  z^2 - c = (b1/a1) tan^2 phi - c.
    1/(z^2-c) dz/g = (1/sqrt(a1 b2)) (1/((b1/a1)tan^2 - c)) dphi/Delta.
    Write in terms of sin^2:  (b1/a1) tan^2 - c = ((b1/a1) sin^2 - c cos^2)/cos^2
      = ((b1/a1 + c) sin^2 - c)/cos^2.
    So integrand = (1/sqrt(a1 b2)) cos^2/(((b1/a1+c)sin^2 - c)) sec^2.. messy.
    Robust: calibrate Pi-atom as d1*Pi(n;phi,m)+d2*F+d3*[alg log/atan] by exact
    derivative match, with n chosen so the Pi-pole sits at z^2=c:
       Pi integrand d/dphi has factor 1/(1-n sin^2 phi); pole at sin^2=1/n.
       sin^2 phi(z) = alpha2 z^2/(1+alpha2 z^2); at z^2=c -> sin^2 = alpha2 c/(1+alpha2 c).
       => n = (1+alpha2 c)/(alpha2 c).
    Then d1 fixed by residue; we calibrate d1,d2 (2 atoms F,Pi) by exact-deriv
    match at 2 points (no algebraic term needed; 1/((z^2-c)g) is pure 3rd+1st)."""
    key = ('_Pi', nstr(c, 30))
    if key not in ch:
        n = (1+ch['alpha2']*c)/(ch['alpha2']*c)
        from mpmath import matrix, lu_solve
        def dPi(z):
            a2z = ch['alpha2']*z*z; al = msqrt(ch['alpha2'])
            dphi = al/(1+a2z); sin2 = a2z/(1+a2z)
            Delta = msqrt(1-ch['m']*sin2)
            return dphi/((1-n*sin2)*Delta)
        def tgt(z):
            return 1/((z*z-c)*gz(ch, z))
        zlo, zhi = ch.get('_zwin', (mpf('0.05'), mpf('0.12')))
        pad = (zhi-zlo)*mpf('0.2')
        zs = [zlo-pad, zhi+pad]
        M = matrix(2, 2); rhs = matrix(2, 1)
        for i, z in enumerate(zs):
            M[i, 0] = dPi(z); M[i, 1] = _dF_dz(ch, z); rhs[i, 0] = tgt(z)
        sol = lu_solve(M, rhs)
        zc = (zlo+zhi)/2
        der = sol[0]*dPi(zc)+sol[1]*_dF_dz(ch, zc)
        cert = abs(der-tgt(zc))/abs(tgt(zc))
        ch[key] = (n, sol[0], sol[1], cert)
    n, d1, d2, cert = ch[key]
    return d1*ellippi(n, phi(ch, z), ch['m']) + d2*ellipf(phi(ch, z), ch['m'])


