out = open(joinpath(@__DIR__, "ginac-comparison.txt"), "w")
function cmp(label, ours::Acb, re::String, im::String)
    target = Acb(Arb(re; prec = prec), Arb(im; prec = prec); prec = prec)
    d = Float64(Arblib.ubound(Arb, abs(ours - target)))
    ok = d < 1e-100
    println(out, label, ": |Eichler - GiNaC| = ", d, "  (<1e-100: ", ok, ")")
    println(label, ": |diff| = ", d, "  agree>100digits: ", ok)
    return ok
end

